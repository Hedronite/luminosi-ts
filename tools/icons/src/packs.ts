// Turns the open-source icon sets in assets/vendor into icon packs:
// packages/icons/src/packs/<id>.ts, one module per pack, plus packs/index.ts (metadata and loaders).
// `bun run icons:packs` writes them; `bun run icons:packs:check` fails if they are stale.
import { existsSync } from "node:fs";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { basename, join, resolve } from "node:path";
import { z } from "zod";
import { convertSvg, humanize, importName, svgFromTsx, type ConvertedIcon, type Paint } from "./packConvert.js";

const root = resolve(import.meta.dirname, "../../..");
const vendor = join(root, "assets/vendor");
const outDir = join(root, "packages/icons/src/packs");

interface Source {
  readonly id: string;
  readonly path: string;
  readonly name?: string;
}

interface PackDefinition {
  readonly id: string;
  readonly name: string;
  readonly description: string;
  readonly license: string;
  readonly credit: string;
  readonly source: string;
  readonly sources: () => Promise<readonly Source[]>;
  readonly tsx?: boolean;
}

const svgFiles = async (dir: string, idOf: (file: string) => string = (f) => f.slice(0, -4)): Promise<Source[]> =>
  (await readdir(join(vendor, dir))).filter((f) => f.endsWith(".svg")).sort().map((f) => ({ id: idOf(f), path: join(vendor, dir, f) }));

const kebab = (pascal: string): string => pascal.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([A-Z])([A-Z][a-z])/g, "$1-$2").toLowerCase();

const stashStyle = (style: string): PackDefinition => ({
  id: `stash-${style}`,
  name: `Stash ${style}`,
  description: `Stash icons, ${style} style.`,
  license: "MIT",
  credit: "Pingback LLC",
  source: "https://github.com/stash-ui/icons",
  tsx: true,
  sources: async () =>
    (await readdir(join(vendor, "stash-icons/packages", style, "src")))
      .filter((f) => f.endsWith("Icon.tsx"))
      .sort()
      .map((f) => ({ id: kebab(basename(f, "Icon.tsx")), path: join(vendor, "stash-icons/packages", style, "src", f) })),
});

const isoconsCatalog = z.array(z.object({ id: z.string(), title: z.string(), category: z.string() }));

const isoconsVariant = (variant: string): PackDefinition => ({
  id: `isocons-${variant.replace(/^edge-/, "")}`,
  name: `Isocons ${variant.replace(/^edge-/, "").replace("-", " ")}`,
  description: `Isometric line icons (isocons.app), the ${variant.replace(/^edge-/, "").replace("-", " ")} variant.`,
  license: "CC-BY-4.0",
  credit: "Isometric Icons by isocons.app (leyeConnect and meandchimso)",
  source: "https://www.isocons.app/",
  sources: async () => {
    const catalog = isoconsCatalog.parse(JSON.parse(await readFile(join(vendor, "isocons/catalog.json"), "utf8")));
    const titles = new Map(catalog.map((entry) => [`${entry.category}/${entry.id}`, entry.title]));
    const categories = (await readdir(join(vendor, "isocons/svg"))).sort();
    const listings = await Promise.all(categories.map(async (category) => ({ category, icons: (await readdir(join(vendor, "isocons/svg", category))).sort() })));
    return listings.flatMap(({ category, icons }) =>
      icons.flatMap((icon): Source[] => {
        const title = titles.get(`${category}/${icon}`);
        const path = join(vendor, "isocons/svg", category, icon, `${variant}.svg`);
        // Not every icon comes in every variant; a variant pack holds the ones that do.
        if (!existsSync(path)) return [];
        return [{ id: icon, path, ...(title === undefined ? {} : { name: title }) }];
      }),
    );
  },
});

export const definitions: readonly PackDefinition[] = [
  { id: "lucide", name: "Lucide", description: "Lucide's stroke icons on a 24-unit grid.", license: "ISC", credit: "Lucide Icons and contributors", source: "https://lucide.dev", sources: () => svgFiles("lucide/icons") },
  { id: "famicons", name: "Famicons", description: "Famicons in filled, outline and sharp styles.", license: "MIT", credit: "Family", source: "https://github.com/familyjs/famicons", sources: () => svgFiles("famicons/src/svg") },
  { id: "coreui", name: "CoreUI Icons", description: "CoreUI Icons Free, linear style.", license: "CC-BY-4.0", credit: "CoreUI (coreui.io)", source: "https://github.com/coreui/coreui-icons", sources: () => svgFiles("coreui-icons/svg/free", (f) => f.slice(0, -4).replace(/^cil-/, "")) },
  stashStyle("regular"),
  stashStyle("light"),
  stashStyle("solid"),
  stashStyle("duotone"),
  stashStyle("editor"),
  ...["edge-rounded-left", "edge-rounded-right", "edge-rounded-top", "edge-sharp-left", "edge-sharp-right", "edge-sharp-top"].map(isoconsVariant),
];

const header = (pack: PackDefinition): string =>
  `// Generated by tools/icons from assets/vendor. Do not edit; run \`bun run icons:packs\`.\n// ${pack.name}: ${pack.source}. License: ${pack.license}. Credit: ${pack.credit}.\n`;

const literal = (paint: Paint): string => JSON.stringify(paint);

async function buildPack(pack: PackDefinition): Promise<{ file: string; count: number }> {
  const sources = await pack.sources();
  const texts = await Promise.all(sources.map((s) => readFile(s.path, "utf8")));
  const viewBoxes = new Map<string, string>();
  const paints = new Map<string, string>();
  const names = new Set<string>();
  const ids = new Set<string>();
  const body: string[] = [];
  sources.forEach((source, index) => {
    const where = `${pack.id}/${source.id}`;
    const text = texts[index] ?? "";
    const icon: ConvertedIcon = convertSvg(pack.tsx === true ? svgFromTsx(text, where) : text, where);
    if (ids.has(source.id)) throw new Error(`${where}: duplicate id`);
    ids.add(source.id);
    const name = importName(source.id);
    if (names.has(name)) throw new Error(`${where}: export name ${name} is taken`);
    names.add(name);
    if (!viewBoxes.has(icon.viewBox)) viewBoxes.set(icon.viewBox, `v${String(viewBoxes.size)}`);
    const paintKey = literal(icon.paint);
    if (!paints.has(paintKey)) paints.set(paintKey, `p${String(paints.size)}`);
    const paths = icon.paths.map((p) => JSON.stringify(p)).join(", ");
    body.push(
      `export const ${name}: PackIcon = { id: ${JSON.stringify(source.id)}, name: ${JSON.stringify(source.name ?? humanize(source.id))}, importName: ${JSON.stringify(name)}, viewBox: ${viewBoxes.get(icon.viewBox) ?? ""}, paint: ${paints.get(paintKey) ?? ""}, paths: [${paths}] };`,
    );
  });
  const info = { id: pack.id, name: pack.name, description: pack.description, count: sources.length, license: pack.license, credit: pack.credit, source: pack.source };
  const file = [
    header(pack),
    'import type { IconPackInfo, PackIcon, PackPaint } from "../pack.js";\n',
    ...[...viewBoxes].map(([value, key]) => `const ${key} = ${JSON.stringify(value)};`),
    ...[...paints].map(([value, key]) => `const ${key}: PackPaint = ${value};`),
    "",
    `export const pack: IconPackInfo = ${JSON.stringify(info)};`,
    "",
    ...body,
    "",
    "/** Every icon in the pack, in id order. Importing this pulls in the whole pack; import icons by name instead. */",
    `export const icons: readonly PackIcon[] = [${[...names].join(", ")}];`,
    "",
  ].join("\n");
  return { file, count: sources.length };
}

async function build(): Promise<Map<string, string>> {
  const outputs = new Map<string, string>();
  const built = await Promise.all(definitions.map(async (pack) => ({ pack, ...(await buildPack(pack)) })));
  for (const { pack, file } of built) outputs.set(join(outDir, `${pack.id}.ts`), file);
  const index = [
    "// Generated by tools/icons from assets/vendor. Do not edit; run `bun run icons:packs`.",
    'import type { IconPackInfo, PackIcon } from "../pack.js";',
    "",
    "/** Every icon pack: what it is, how many icons, its license and credit. Small; loads no icons. */",
    `export const iconPacks: readonly IconPackInfo[] = ${JSON.stringify(
      built.map(({ pack, count }) => ({ id: pack.id, name: pack.name, description: pack.description, count, license: pack.license, credit: pack.credit, source: pack.source })),
      null,
      2,
    )};`,
    "",
    "/** Loads a pack's icons on demand (each pack is its own chunk). */",
    "export const loadIconPack: Readonly<Record<string, () => Promise<{ readonly pack: IconPackInfo; readonly icons: readonly PackIcon[] }>>> = {",
    ...built.map(({ pack }) => `  ${JSON.stringify(pack.id)}: () => import("./${pack.id}.js"),`),
    "};",
    "",
  ].join("\n");
  outputs.set(join(outDir, "index.ts"), index);
  return outputs;
}

const outputs = [...(await build())];
if (process.argv.includes("--check")) {
  const current = await Promise.all(outputs.map(([path]) => readFile(path, "utf8").catch(() => "")));
  const stale = outputs.filter(([, content], i) => current[i] !== content).map(([path]) => path.slice(root.length + 1));
  if (stale.length > 0) {
    console.error(`Generated icon packs are stale: ${stale.join(", ")}. Run \`bun run icons:packs\`.`);
    process.exit(1);
  }
  console.log(`icon packs: ${String(outputs.length)} generated files up to date`);
} else {
  await Promise.all(outputs.map(([path, content]) => writeFile(path, content)));
  console.log(`icon packs: wrote ${String(outputs.length)} files`);
}
