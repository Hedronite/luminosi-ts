// Turns assets/src/icons/*.svg into packages/icons/src/generated/*.
// `bun run icons` writes the files; `bun run icons:check` fails if they are stale.
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { optimize } from "svgo";
import { z } from "zod";

const root = resolve(import.meta.dirname, "../../..");
const sourceDir = join(root, "assets/src/icons");
const outDir = join(root, "packages/icons/src");
const assetVersion = "0.1.0";

const metaSchema = z.record(
  z.string().regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/),
  z.object({ name: z.string().min(1), tags: z.array(z.string()).min(1), added: z.iso.date() }).strict(),
);

const header = "// Generated by tools/icons from assets/src/icons. Do not edit; run `bun run icons`.\n";

const camel = (id: string): string => id.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
const pascal = (id: string): string => camel(id).replace(/^[a-z]/, (c) => c.toUpperCase());

const num = (attrs: string, name: string): number => {
  const match = new RegExp(`\\b${name}="([\\d.]+)"`).exec(attrs);
  return match === null ? 0 : Number(match[1]);
};

/** SVGO leaves rounded rects alone, so turn `<rect rx>` into an arc path first. */
function roundedRectsToPaths(svg: string): string {
  return svg.replace(/<rect\b([^>]*)\/>/g, (whole, attrs: string) => {
    const r = num(attrs, "rx");
    if (r === 0) return whole;
    const [x, y, w, h] = [num(attrs, "x"), num(attrs, "y"), num(attrs, "width"), num(attrs, "height")];
    const [hw, hh] = [w - 2 * r, h - 2 * r];
    const arc = (dx: number, dy: number): string => `a${String(r)} ${String(r)} 0 0 1 ${String(dx)} ${String(dy)}`;
    return `<path d="M${String(x + r)} ${String(y)}h${String(hw)}${arc(r, r)}v${String(hh)}${arc(-r, r)}h${String(-hw)}${arc(-r, -r)}v${String(-hh)}${arc(r, -r)}z"/>`;
  });
}

/** Optimizes one SVG and returns its path data. Every shape becomes a path. */
function toPaths(id: string, svg: string): string[] {
  if (!/viewBox="0 0 24 24"/.test(svg)) {
    throw new Error(`${id}.svg: viewBox must be "0 0 24 24"`);
  }
  const { data } = optimize(roundedRectsToPaths(svg), {
    multipass: true,
    plugins: [{ name: "preset-default", params: { overrides: { convertShapeToPath: { convertArcs: true } } } }],
  });
  const leftover = /<(circle|ellipse|rect|line|polyline|polygon|g|use|text)\b/.exec(data);
  if (leftover !== null) {
    throw new Error(`${id}.svg: <${leftover[1] ?? "?"}> was not converted to a path`);
  }
  const paths = [...data.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1] ?? "");
  if (paths.length === 0 || paths.includes("")) {
    throw new Error(`${id}.svg: no path data`);
  }
  return paths;
}

async function build(): Promise<Map<string, string>> {
  const meta = metaSchema.parse(JSON.parse(await readFile(join(sourceDir, "icons.json"), "utf8")));
  const files = (await readdir(sourceDir)).filter((f) => f.endsWith(".svg")).sort();
  const ids = files.map((f) => f.slice(0, -".svg".length));

  const missing = ids.filter((id) => !(id in meta));
  const orphans = Object.keys(meta).filter((id) => !ids.includes(id));
  if (missing.length > 0 || orphans.length > 0) {
    throw new Error(`icons.json out of sync. Missing: ${missing.join(", ") || "none"}. No SVG: ${orphans.join(", ") || "none"}`);
  }

  const icons = await Promise.all(
    ids.map(async (id) => ({ id, paths: toPaths(id, await readFile(join(sourceDir, `${id}.svg`), "utf8")) })),
  );

  const data = [
    header,
    'import type { IconData } from "../icon.js";\n',
    ...icons.map(({ id, paths }) => {
      const m = meta[id];
      return `\nexport const ${camel(id)}: IconData = {\n  id: ${JSON.stringify(id)},\n  name: ${JSON.stringify(m?.name)},\n  paths: [${paths.map((p) => JSON.stringify(p)).join(", ")}],\n};\n`;
    }),
  ].join("");

  const names = ids.map(camel);
  const manifest = [
    header,
    'import type { IconData } from "../icon.js";\n',
    `import { ${names.join(", ")} } from "./icons.js";\n\n`,
    "/** Every icon, in id order. Importing this pulls in the whole set; import icons by name instead. */\n",
    `export const allIcons: readonly IconData[] = [${names.join(", ")}];\n\n`,
    "/** The icon set's manifest for the LuminosiTS registry (`registerManifest`). */\n",
    "export const manifest = {\n",
    '  package: "@hedronite/lts-icons",\n',
    "  assets: [\n",
    ...ids.map((id) => {
      const m = meta[id];
      return `    { id: ${JSON.stringify(id)}, kind: "icon", name: ${JSON.stringify(m?.name)}, version: "${assetVersion}", tags: ${JSON.stringify(m?.tags)}, added: ${JSON.stringify(m?.added)} },\n`;
    }),
    "  ],\n",
    "} as const;\n",
  ].join("");

  const react = [
    header,
    `import { ${names.join(", ")} } from "../generated/icons.js";\n`,
    'import { Icon, type IconProps } from "./Icon.js";\n',
    ...ids.map((id) => `\nexport function ${pascal(id)}(props: IconProps) {\n  return <Icon icon={${camel(id)}} {...props} />;\n}\n`),
  ].join("");

  return new Map([
    [join(outDir, "generated/icons.ts"), data],
    [join(outDir, "generated/manifest.ts"), manifest],
    [join(outDir, "react/generated.tsx"), react],
  ]);
}

const outputs = [...(await build())];
if (process.argv.includes("--check")) {
  const current = await Promise.all(outputs.map(([path]) => readFile(path, "utf8").catch(() => "")));
  const stale = outputs.filter(([, content], i) => current[i] !== content).map(([path]) => path.slice(root.length + 1));
  if (stale.length > 0) {
    console.error(`Generated icon files are stale: ${stale.join(", ")}. Run \`bun run icons\`.`);
    process.exit(1);
  }
  console.log(`icons: ${String(outputs.length)} generated files up to date`);
} else {
  await Promise.all(outputs.map(([path, content]) => writeFile(path, content)));
  console.log(`icons: wrote ${String(outputs.length)} files`);
}
