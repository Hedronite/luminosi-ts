// Turns assets/src/objects/*.json (ObjectSpecs, usually emitted by the forge) into
// packages/objects/src/generated/objects.ts. `bun run objects` writes it; `bun run objects:check`
// fails if it is stale. Each spec is validated with parseObjectSpec first, so a bad spec never
// reaches the library. Needs @hedronite/lts-objects built (bun run build).
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { parseObjectSpec } from "@hedronite/lts-objects";
import { z } from "zod";

const root = resolve(import.meta.dirname, "../../..");
const sourceDir = join(root, "assets/src/objects");
const outFile = join(root, "packages/objects/src/generated/objects.ts");

const metaSchema = z.record(
  z.string().regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/),
  z.object({ name: z.string().min(1).max(80), tags: z.array(z.string().regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/)).min(1), added: z.iso.date(), source: z.string().min(1) }).strict(),
);

async function build(): Promise<string> {
  const meta = metaSchema.parse(JSON.parse(await readFile(join(sourceDir, "objects.json"), "utf8")));
  const files = (await readdir(sourceDir)).filter((f) => f.endsWith(".json") && f !== "objects.json").sort();
  const ids = Object.keys(meta).sort();
  const listed = new Set(ids);
  for (const file of files) {
    if (!listed.has(file.slice(0, -5))) throw new Error(`assets/src/objects/${file} has no entry in objects.json`);
  }
  for (const id of ids) {
    if (!files.includes(`${id}.json`)) throw new Error(`objects.json lists "${id}" but assets/src/objects/${id}.json is missing`);
  }
  const texts = await Promise.all(ids.map((id) => readFile(join(sourceDir, `${id}.json`), "utf8")));
  const entries: string[] = [];
  for (const [index, id] of ids.entries()) {
    const entry = meta[id];
    if (entry === undefined) continue;
    const raw: unknown = JSON.parse(texts[index] ?? "null");
    const spec = parseObjectSpec(raw);
    if (spec.id !== id) throw new Error(`assets/src/objects/${id}.json has id "${spec.id}"; it must match the file name`);
    entries.push(`  ${JSON.stringify({ id, name: entry.name, tags: entry.tags, added: entry.added, source: entry.source, spec: raw })},`);
  }
  return [
    "// Generated by tools/objects from assets/src/objects. Do not edit; run `bun run objects`.",
    "",
    "/** A library object stored as data: its metadata and its ObjectSpec, as written (parse before use). */",
    "export interface GeneratedObject {",
    "  readonly id: string;",
    "  readonly name: string;",
    "  readonly tags: readonly string[];",
    "  readonly added: string;",
    "  readonly source: string;",
    "  readonly spec: unknown;",
    "}",
    "",
    "export const generatedObjects: readonly GeneratedObject[] = [",
    ...entries,
    "];",
    "",
  ].join("\n");
}

const output = await build();
if (process.argv.includes("--check")) {
  const current = await readFile(outFile, "utf8").catch(() => "");
  if (current !== output) {
    console.error("packages/objects/src/generated/objects.ts is stale: run `bun run objects`");
    process.exit(1);
  }
  console.log("objects: up to date");
} else {
  await writeFile(outFile, output);
  console.log(`objects: wrote ${outFile.slice(root.length + 1)}`);
}
