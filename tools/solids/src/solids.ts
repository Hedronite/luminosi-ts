// The solids tool: assets/src/solids → packages/primitives/src/generated/archimedean.ts.
//   bun run solids          regenerate it
//   bun run solids:check    fail if it is stale
// The source holds vertices only; the hull (faces) is found here, once, because the brute-force hull is
// too slow to run in a browser for the 120-vertex truncated icosidodecahedron.
import { readFile, writeFile } from "node:fs/promises";
import { join, relative, resolve } from "node:path";
import { convexHull } from "../../../packages/primitives/src/polyhedron.js";
import type { Vec3 } from "../../../packages/primitives/src/vec.js";

const root = resolve(import.meta.dirname, "../../..");
const sourceFile = join(root, "assets/src/solids/archimedean.json");
const outFile = join(root, "packages/primitives/src/generated/archimedean.ts");

/** Faces each Archimedean solid has: a hull that finds a different number is wrong. */
const expectedFaces: Readonly<Record<string, number>> = {
  "truncated-tetrahedron": 8,
  cuboctahedron: 14,
  "truncated-cube": 14,
  "truncated-octahedron": 14,
  rhombicuboctahedron: 26,
  "truncated-cuboctahedron": 26,
  "snub-cube": 38,
  icosidodecahedron: 32,
  "truncated-dodecahedron": 32,
  "truncated-icosahedron": 32,
  rhombicosidodecahedron: 62,
  "truncated-icosidodecahedron": 62,
  "snub-dodecahedron": 92,
};

const isVec3 = (value: unknown): value is Vec3 => Array.isArray(value) && value.length === 3 && value.every((c) => typeof c === "number" && Number.isFinite(c));

async function solids(): Promise<readonly (readonly [string, Vec3[]])[]> {
  const parsed: unknown = JSON.parse(await readFile(sourceFile, "utf8"));
  const table = typeof parsed === "object" && parsed !== null && "solids" in parsed ? parsed.solids : undefined;
  if (typeof table !== "object" || table === null) throw new Error(`${relative(root, sourceFile)}: no "solids" table`);
  const entries = Object.entries(table).map(([id, points]): [string, Vec3[]] => {
    if (!Array.isArray(points) || !points.every(isVec3)) throw new Error(`${relative(root, sourceFile)}: "${id}" is not a list of [x, y, z]`);
    return [id, points];
  });
  const ids = entries.map(([id]) => id);
  const missing = Object.keys(expectedFaces).filter((id) => !ids.includes(id));
  const unknown = ids.filter((id) => expectedFaces[id] === undefined);
  if (missing.length > 0 || unknown.length > 0) throw new Error(`${relative(root, sourceFile)}: missing [${missing.join(", ")}], unknown [${unknown.join(", ")}]`);
  return entries;
}

/**
 * A face turned to start at its lowest vertex index, keeping its winding. The hull orders a face by
 * angle, and where a vertex sits at exactly ±180° the last bit of atan2 can differ between platforms;
 * a fixed starting point makes the output the same everywhere.
 */
function fromLowest(face: readonly number[]): readonly number[] {
  const start = face.indexOf(Math.min(...face));
  return [...face.slice(start), ...face.slice(0, start)];
}

function render(all: readonly (readonly [string, Vec3[]])[]): string {
  const lines = [
    "// Generated by tools/solids from assets/src/solids. Do not edit; run `bun run solids`.",
    "// Vertices come from hedronite.com (unit circumradius); faces are their convex hull, counter-clockwise from outside.",
    'import type { Polyhedron } from "../polyhedron.js";',
    "",
    `export const archimedeanSolids = [${all.map(([id]) => JSON.stringify(id)).join(", ")}] as const;`,
    "export type ArchimedeanSolid = (typeof archimedeanSolids)[number];",
    "",
    "export const archimedeanData: Readonly<Record<ArchimedeanSolid, Polyhedron>> = {",
  ];
  for (const [id, points] of all) {
    const hull = convexHull(points);
    if (hull.faces.length !== expectedFaces[id]) throw new Error(`${id}: the hull has ${String(hull.faces.length)} faces, expected ${String(expectedFaces[id])}`);
    lines.push(`  ${JSON.stringify(id)}: {`, `    vertices: ${JSON.stringify(points)},`, `    faces: ${JSON.stringify(hull.faces.map(fromLowest))},`, "  },");
  }
  lines.push("};", "");
  return lines.join("\n");
}

const [command = ""] = process.argv.slice(2);
if (command === "generate" || command === "check") {
  const output = render(await solids());
  if (command === "check") {
    const current = await readFile(outFile, "utf8").catch(() => "");
    if (current !== output) {
      console.error(`${relative(root, outFile)} is stale: run \`bun run solids\``);
      process.exit(1);
    }
    console.log("solids: up to date");
  } else {
    await writeFile(outFile, output);
    console.log(`solids: wrote ${relative(root, outFile)}`);
  }
} else {
  console.error("usage: bun src/solids.ts generate | check");
  process.exit(2);
}
